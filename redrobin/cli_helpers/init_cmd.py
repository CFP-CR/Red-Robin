"""redrobin init - first-time operator setup.

Creates ~/.redrobin/ layout, optionally prompts the operator for API keys
(with hidden input via :mod:`getpass`), and drops an example engagement plus
a sample rule. Idempotent: re-running never clobbers existing files.

Audit pass 1 finding #7: :func:`getpass.getpass` falls back to plain-text echo
(emitting a :class:`GetPassWarning`) when the controlling terminal is not a
true TTY. This bites operators on Git Bash / MSYS2 and on any subprocess
invocation whose stdin is not a TTY (CI, ``< file`` redirection, etc). The
interactive flow therefore:

* Refuses to prompt at all when ``sys.stdin.isatty()`` is False, exiting 2
  and pointing the operator at ``--non-interactive`` with the explicit
  ``--anthropic-key`` / ``--voyage-key`` flags.
* Warns (but does not fail) when ``MSYSTEM`` is set, recommending Windows
  Terminal or PowerShell for secret entry.
"""

from __future__ import annotations

import getpass
import os
import sys
from pathlib import Path

_ENV_TEMPLATE = """\
# Red Robin local configuration (generated by `redrobin init`).
# Explicit shell env vars OVERRIDE these values.

ANTHROPIC_API_KEY={anthropic}
VOYAGE_API_KEY={voyage}

REDROBIN_HOST=127.0.0.1
REDROBIN_PORT=7777

REDROBIN_ROOT={root}
REDROBIN_ENGAGEMENT_SLUG={slug}

REDROBIN_L5_WINDOW=25
REDROBIN_L5_INTERVAL_SEC=30

# The assistant is off by default in code (it was dark-launched). You just gave
# init your API keys, so it is on here. Set to 0 for a capture-only setup.
REDROBIN_ASSISTANT_ENABLED=1

REDROBIN_ALLOW_DEGRADED=0
"""

_ENGAGEMENT_TEMPLATE = """\
slug: {slug}
name: {slug}
in_scope:
  - corp.local
out_of_scope:
  - bigcorp.com
summary: |
  Replace this with your engagement-specific OPSEC context (low-detection
  priority, EDR vendor, prior tradecraft constraints, etc.) so it travels
  with the engagement and is visible to whoever picks it up next.
"""


def run_init(
    *,
    root: Path,
    anthropic_key: str | None = None,
    voyage_key: str | None = None,
    engagement_slug: str = "op-default",
    interactive: bool = True,
) -> int:
    root = Path(root).expanduser()

    if interactive:
        # Audit finding #7: getpass on Git Bash / non-TTY echoes plain text.
        # Refuse to prompt interactively in those environments.
        if not sys.stdin.isatty():
            print(
                "ERROR: stdin is not a TTY. Use --non-interactive with "
                "--anthropic-key and --voyage-key to set the keys explicitly, "
                "or run from an interactive shell.",
                file=sys.stderr,
            )
            return 2
        if os.environ.get("MSYSTEM"):  # Git Bash / MSYS2 on Windows
            print(
                "WARN: Git Bash / MSYS2 detected. getpass may echo input in "
                "plain text on this environment. For secret entry use Windows "
                "Terminal or PowerShell, or pass --anthropic-key / --voyage-key "
                "explicitly.",
                file=sys.stderr,
            )

        print(f"Red Robin setup - root will be: {root}")
        if anthropic_key is None:
            anthropic_key = getpass.getpass("ANTHROPIC_API_KEY (input hidden): ").strip()
        if voyage_key is None:
            voyage_key = getpass.getpass("VOYAGE_API_KEY (input hidden): ").strip()
        ans = input(f"Engagement slug [{engagement_slug}]: ").strip()
        if ans:
            engagement_slug = ans

    # Layout
    for sub in ("engagements",):
        (root / sub).mkdir(parents=True, exist_ok=True)
    eng_dir = root / "engagements" / engagement_slug
    eng_dir.mkdir(parents=True, exist_ok=True)

    # engagement.yaml (idempotent - don't clobber)
    eng_file = eng_dir / "engagement.yaml"
    if not eng_file.exists():
        eng_file.write_text(_ENGAGEMENT_TEMPLATE.format(slug=engagement_slug))

    # .env (idempotent + chmod 600)
    env_file = root / ".env"
    if not env_file.exists():
        env_file.write_text(
            _ENV_TEMPLATE.format(
                anthropic=anthropic_key or "",
                voyage=voyage_key or "",
                root=root,
                slug=engagement_slug,
            )
        )
        if sys.platform != "win32":
            env_file.chmod(0o600)

    print("\nDone. Next steps:")
    print(f"  cd {root}")
    print("  redrobin doctor    # verify setup")
    print("  redrobin daemon start")
    return 0
